/**
 * Imports tiered prompt files from `content/inbox/*.txt` into the content
 * catalog.
 *
 * Format
 *   line 1            the question
 *   blank line        starts the next rarity tier
 *   Name|alias, alias optional aliases, comma separated
 *   # ...             ignored
 *
 * Tiers run most common -> rarest and map to
 * forager / soldier / royal / queen / apex. Any further tiers stay apex.
 *
 * Usage
 *   npm run content:import               # regenerate every inbox file
 *   npm run content:import -- --dry-run  # report only, write nothing
 *   npm run content:import -- --reverse  # file lists rarest tier first
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const INBOX = path.join(ROOT, "content", "inbox");
const OUT = path.join(ROOT, "content", "catalog", "imported.ts");
const CONFIG = path.join(ROOT, "src", "lib", "config.ts");
const RARITIES = ["forager", "soldier", "royal", "queen", "apex"] as const;

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const reverse = args.includes("--reverse");
const packArg = args.find((arg) => arg.startsWith("--pack="));
const pack = packArg ? packArg.slice("--pack=".length) : "geography";

type ImportedPrompt = {
  slug: string;
  text: string;
  pack: string;
  scope: string;
  tiers: string[][];
};

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 40);
}

function parseFile(file: string): ImportedPrompt {
  const raw = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const lines = raw
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => !line.startsWith("#"));

  const first = lines.findIndex((line) => line.length > 0);
  if (first < 0) throw new Error(`${file}: file is empty`);

  const text = lines[first].replace(/\s+/g, " ");
  const tiers: string[][] = [];
  let current: string[] = [];

  for (const line of lines.slice(first + 1)) {
    if (!line) {
      if (current.length) tiers.push(current);
      current = [];
      continue;
    }
    if (current.includes(line)) throw new Error(`${file}: "${line}" appears twice in one tier`);
    current.push(line);
  }
  if (current.length) tiers.push(current);

  if (tiers.length < 2) {
    throw new Error(`${file}: needs at least two tiers separated by a blank line`);
  }
  if (tiers.length > RARITIES.length) {
    throw new Error(`${file}: ${tiers.length} tiers, but only ${RARITIES.length} rarities exist`);
  }

  const tiersOut = reverse ? [...tiers].reverse() : tiers;
  const seen = new Map<string, number>();
  tiersOut.forEach((tier, index) => {
    for (const answer of tier) {
      const key = answer.split("|")[0]!.trim().toLowerCase();
      const previous = seen.get(key);
      if (previous !== undefined) {
        throw new Error(`${file}: "${answer}" already used in tier ${previous + 1}`);
      }
      seen.set(key, index);
    }
  });

  const base = path.basename(file, ".txt");
  return {
    slug: slugify(base),
    text,
    pack,
    scope: `Accepted answers for “${text}”, grouped into ${tiers.length} rarity tiers.`,
    tiers: tiersOut,
  };
}

function main() {
  if (!existsSync(INBOX)) {
    console.error(`[import] no inbox at ${path.relative(ROOT, INBOX)}`);
    process.exit(1);
  }
  const files = readdirSync(INBOX)
    .filter((name) => name.toLowerCase().endsWith(".txt"))
    .sort();

  if (!files.length) {
    console.error("[import] no .txt files in content/inbox");
    process.exit(1);
  }

  const prompts = files.map((name) => parseFile(path.join(INBOX, name)));

  const total = prompts.reduce((sum, prompt) => sum + prompt.tiers.reduce((n, tier) => n + tier.length, 0), 0);
  for (const prompt of prompts) {
    const counts = prompt.tiers.map((tier, index) => `${RARITIES[index]} ${tier.length}`).join(" · ");
    console.log(`[import] ${prompt.slug.padEnd(28)} "${prompt.text}" — ${counts}`);
  }
  console.log(`[import] ${prompts.length} prompt(s), ${total} answers`);

  if (dryRun) {
    console.log("[import] dry run: nothing written");
    return;
  }

  const body = `/**
 * Generated by scripts/import-prompts.ts.
 * Edit content/inbox/*.txt and re-run npm run content:import instead of
 * changing this file by hand.
 */

export type ImportedPrompt = {
  slug: string;
  text: string;
  pack: string;
  scope: string;
  tiers: string[][];
};

export const IMPORTED_PROMPTS: ImportedPrompt[] = ${JSON.stringify(prompts, null, 2)};
`;

  const previous = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  writeFileSync(OUT, body);

  if (previous === body) {
    console.log("[import] catalog unchanged; content version left alone");
    return;
  }

  const config = readFileSync(CONFIG, "utf8");
  const match = config.match(/export const CONTENT_VERSION = "(\d{4})\.(\d{1,2})\.(\d{1,3})";/);
  if (!match) {
    console.warn("[import] could not find CONTENT_VERSION; bump it by hand so the next seed runs");
    return;
  }
  const next = `${match[1]}.${match[2]}.${Number(match[3]) + 1}`;
  writeFileSync(
    CONFIG,
    config.replace(match[0], `export const CONTENT_VERSION = "${next}";`),
  );
  console.log(`[import] wrote ${path.relative(ROOT, OUT)} — CONTENT_VERSION ${match[1]}.${match[2]}.${match[3]} -> ${next}`);
  console.log("[import] run npm run db:seed to load it into the database");
}

main();
